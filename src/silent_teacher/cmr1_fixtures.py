"""CMR1 governed fixture construction: calibration fixtures, the formal fixture and the Q_pos pair.

Every construction law here is transcribed from the frozen contracts:

* ``CS-CAL-1`` / ``CS-CAL-2`` (B4): 2 calibration examples x 128 positions, float32, direct synthetic
  hidden-state tensors at the block-5 boundary, drawn iid standard normal.  CS-CAL-2 is the same law
  followed by projection to q/k by the production projection layer.  The two fixtures are
  **unconditionally distinct** - no sharing, merging or substitution path exists.
* ``fixture/formal`` (B4 Q3): 256 sequences x 128 positions generated by the frozen Native sampling
  law (accepted token-ID set ``0..50276``, iid uniform **with replacement**), pushed through the
  pinned Teacher prefix; targets are the declared Teacher block-5 residual update.
* Q_pos (protocol 6.1/6.2): ``H_pos[n,t] = H_nat[pi_t(n), t]`` with, independently for each position,
  a **uniform** permutation ``pi_t`` over donor indices, **not** derangement-constrained; the Native
  bank is never regenerated for the Q_pos arm.

The canonical construction path requires a committed phase-scoped capability, an attested runtime
context, and the pinned Teacher identity where applicable. No governed fixture is realized by importing
this module or by the TEST-ONLY tests.
"""
from __future__ import annotations

from typing import Mapping

import torch

from silent_teacher import cmr1_objects, cmr1_rng, cmr1_teacher

# --------------------------------------------------------------------------- frozen shapes
CALIBRATION_EXAMPLES = 2
CALIBRATION_LENGTH = 128
FORMAL_SEQUENCES = 256
FORMAL_LENGTH = 128

#: B4 Q2-1/Q2-4 qualification-phase queries (B8 ``query_positions``, frozen).
QUERY_POSITIONS: tuple[int, int] = (63, 127)

#: B2 token policy: accepted token-ID set is ``range(0, 50277)``.
ACCEPTED_TOKEN_MIN = 0
ACCEPTED_TOKEN_MAX_EXCLUSIVE = 50277

FIXTURE_DTYPE = torch.float32


#: Canonical owning roles for the two calibration fixtures (B4 CS-CAL-1 / CS-CAL-2 as bound by the
#: approved amendment).  Each governed builder is bound to its own role.
ROLE_CALIBRATION_Q2_1 = "calibration/q2-1"
ROLE_CALIBRATION_Q2_4 = "calibration/q2-4"


def _require_calibration_role(role: str, expected: str) -> None:
    """Reject a role mismatch: a calibration fixture may only be realised under its own identity."""
    if role != expected:
        raise FixtureConstructionError(
            f"HARD STOP - CALIBRATION FIXTURE IDENTITY CONFLATION: this builder is bound to "
            f"{expected!r} and refuses role {role!r}; the two calibration fixtures are DISTINCT and "
            "may never be merged, substituted or realised under each other's identity")


class FixtureConstructionError(RuntimeError):
    """A frozen fixture construction law was violated."""


class GovernedFixtureNotAuthorized(RuntimeError):
    """Raised when a caller asks for a governed (canonical-namespace) fixture realization."""


def _refuse_governed(namespace: str, what: str, *, capability=None,
                     runtime_context=None, teacher=None) -> None:
    if not cmr1_rng.is_canonical_qualification_namespace(namespace):
        cmr1_rng.require_test_only_namespace(namespace)
        return
    from silent_teacher import cmr1_authorization, cmr1_bootstrap, cmr1_teacher
    scope = cmr1_authorization.SCOPE_QUALIFICATION_IDENTITY_REALIZATION
    if not cmr1_authorization.capability_authorizes(capability, scope):
        raise GovernedFixtureNotAuthorized(
            f"{what} requires a committed phase-scoped capability; no governed realization "
            "is authorized by implementation repair")
    if teacher is not None:
        cmr1_teacher.assert_pinned_teacher_wrapper(teacher)
    cmr1_bootstrap.assert_governed_entry(runtime_context, scope=scope,
                                          teacher=teacher.model if teacher is not None else None)


def _generator(seed: int) -> torch.Generator:
    """A CPU generator seeded from one B9 role seed.

    The role seed already identifies the role uniquely, so no additional salt is mixed in - adding
    one would create an undeclared derivation rule.
    """
    if type(seed) is not int or not 0 <= seed < cmr1_rng.MODULUS:
        raise FixtureConstructionError("B9 role seed must be a canonical integer in [0, 2**63-1)")
    generator = torch.Generator(device="cpu")
    generator.manual_seed(seed)
    return generator


# --------------------------------------------------------------------------- CS-CAL-1 / CS-CAL-2
def build_calibration_fixture_q2_1(role_seed: int, *, namespace: str,
                                   role: str = ROLE_CALIBRATION_Q2_1,
                                   capability=None, runtime_context=None) -> torch.Tensor:
    """CS-CAL-1: ``[2, 128, 768]`` float32 hidden states, iid standard normal.

    Direct synthetic hidden tensors at the block-5 boundary: no tokenizer, no upstream prefix, no
    target data.

    **Role binding:** this builder is bound to ``calibration/q2-1`` and rejects any other role, so a
    caller cannot realise the Q2-1 fixture under the Q2-4 identity (or vice versa).
    """
    _require_calibration_role(role, ROLE_CALIBRATION_Q2_1)
    _refuse_governed(namespace, "Q2-1 calibration fixture", capability=capability,
                     runtime_context=runtime_context)
    generator = _generator(role_seed)
    tensor = torch.randn(CALIBRATION_EXAMPLES, CALIBRATION_LENGTH, 768,
                         generator=generator, dtype=FIXTURE_DTYPE)
    assert_calibration_fixture(tensor, label="CS-CAL-1")
    return tensor


def build_calibration_fixture_q2_4(role_seed: int, *, namespace: str,
                                   role: str = ROLE_CALIBRATION_Q2_4,
                                   width: int = 768, capability=None, runtime_context=None) -> torch.Tensor:
    """CS-CAL-2: ``[2, 128, 768]`` float32 hidden states under the same law as CS-CAL-1.

    The schema's projection to q/k is applied later by the production projection layer; the fixture
    itself is the hidden-state tensor.
    """
    _refuse_governed(namespace, "Q2-4 calibration fixture", capability=capability,
                     runtime_context=runtime_context)
    _require_calibration_role(role, ROLE_CALIBRATION_Q2_4)
    generator = _generator(role_seed)
    tensor = torch.randn(CALIBRATION_EXAMPLES, CALIBRATION_LENGTH, width,
                         generator=generator, dtype=FIXTURE_DTYPE)
    assert_calibration_fixture(tensor, label="CS-CAL-2")
    return tensor


def assert_calibration_fixture(tensor: torch.Tensor, *, label: str) -> None:
    """Structural assertions common to both calibration fixtures."""
    if tensor.dtype != FIXTURE_DTYPE:
        raise FixtureConstructionError(f"{label} must be float32, got {tensor.dtype}")
    if tensor.shape != (CALIBRATION_EXAMPLES, CALIBRATION_LENGTH, 768):
        raise FixtureConstructionError(
            f"{label} must have shape (2, 128, 768), got {tuple(tensor.shape)}")
    if not torch.isfinite(tensor).all():
        raise FixtureConstructionError(f"{label} contains non-finite values")


def calibration_fixture_identity(tensor: torch.Tensor, *, role: str) -> str:
    if role not in (ROLE_CALIBRATION_Q2_1, ROLE_CALIBRATION_Q2_4):
        raise FixtureConstructionError("unknown calibration fixture role")
    assert_calibration_fixture(tensor, label=role)
    return cmr1_objects.tensor_object_identity(
        {"hidden": tensor},
        semantics={"hidden": "distinct CMR1 calibration hidden fixture, iid standard normal, FP32"},
        extra={"role": role, "shape": [CALIBRATION_EXAMPLES, CALIBRATION_LENGTH, 768]})


def assert_calibration_fixtures_distinct(q2_1: torch.Tensor, q2_4: torch.Tensor) -> None:
    """The two calibration fixtures must be distinct objects with distinct content."""
    if q2_1.shape != q2_4.shape:
        raise FixtureConstructionError("calibration fixtures must share a shape but not content")
    if torch.equal(q2_1, q2_4):
        raise FixtureConstructionError(
            "HARD STOP - CALIBRATION FIXTURE IDENTITY CONFLATION: the two calibration fixtures "
            "must be DISTINCT; sharing, merging and substitution are forbidden")


# --------------------------------------------------------------------------- fixture/formal
def sample_native_token_ids(role_seed: int, *, sequences: int = FORMAL_SEQUENCES,
                            length: int = FORMAL_LENGTH,
                            generator: torch.Generator | None = None) -> torch.Tensor:
    """Frozen Native sampling law: accepted token IDs ``0..50276``, iid uniform **with replacement**."""
    if sequences <= 0 or length <= 0:
        raise FixtureConstructionError("fixture dimensions must be positive")
    if generator is None:
        generator = _generator(role_seed)
    span = ACCEPTED_TOKEN_MAX_EXCLUSIVE - ACCEPTED_TOKEN_MIN
    ids = torch.randint(ACCEPTED_TOKEN_MIN, ACCEPTED_TOKEN_MIN + span,
                        (sequences, length), generator=generator, dtype=torch.int64)
    assert_accepted_token_ids(ids)
    return ids


def assert_accepted_token_ids(ids: torch.Tensor) -> None:
    """Every id must lie in the frozen accepted set, and the shape must be the frozen shape."""
    if ids.dtype != torch.int64:
        raise FixtureConstructionError(f"token ids must be int64, got {ids.dtype}")
    if ids.shape != (FORMAL_SEQUENCES, FORMAL_LENGTH):
        raise FixtureConstructionError(
            f"fixture must be {FORMAL_SEQUENCES} x {FORMAL_LENGTH}, got {tuple(ids.shape)}")
    if int(ids.min()) < ACCEPTED_TOKEN_MIN or int(ids.max()) >= ACCEPTED_TOKEN_MAX_EXCLUSIVE:
        raise FixtureConstructionError(
            f"token ids outside the accepted set "
            f"[{ACCEPTED_TOKEN_MIN}, {ACCEPTED_TOKEN_MAX_EXCLUSIVE})")


class FixtureProvenanceError(RuntimeError):
    """The formal fixture's provenance chain is broken or unverifiable."""


def build_formal_fixture(role_seed: int, *, namespace: str, teacher,
                         device: str = "cpu", position_ids=None,
                         capability=None, runtime_context=None) -> dict:
    """Build the formal fixture through **one bound provenance chain**.

    ::

        fixture/formal role identity
          -> exact accepted token ids        (frozen Native law, set 0..50276)
          -> frozen Teacher prefix blocks 0-4
          -> exact block-5 input hidden states
          -> exact frozen Teacher block-5 residual update / target
          -> formal fixture object + provenance record

    There is deliberately **no** parameter accepting externally supplied Teacher hidden states or
    updates.  A caller cannot attach unrelated Teacher tensors to a token bank: the hidden states and
    targets are computed here from the sampled ids by the frozen Teacher path, and the provenance
    record lets :func:`assert_fixture_provenance` prove that binding later.

    ``teacher`` must expose the frozen Teacher interface -- ``prefix_states(token_ids)`` and
    ``residual_update(hidden)`` -- i.e. the production ``BlockFiveWrapper``.
    """
    _refuse_governed(namespace, "formal fixture", capability=capability,
                     runtime_context=runtime_context, teacher=teacher)
    if position_ids is not None:
        raise FixtureProvenanceError("formal fixture position IDs are fixed by the Teacher input path")
    for method in ("prefix_states", "residual_update"):
        if not callable(getattr(teacher, method, None)):
            raise FixtureProvenanceError(
                f"the formal fixture requires the frozen Teacher interface; {method!r} is missing")

    token_ids = sample_native_token_ids(role_seed)
    assert_accepted_token_ids(token_ids)

    hidden_raw = (teacher.capture_boundary(token_ids.to(device))
                  if cmr1_rng.is_canonical_qualification_namespace(namespace)
                  else teacher.prefix_states(token_ids.to(device)))
    if not isinstance(hidden_raw, torch.Tensor) or hidden_raw.dtype != FIXTURE_DTYPE:
        raise FixtureProvenanceError("Teacher prefix output must already be FP32; no silent cast")
    hidden = hidden_raw.detach().to("cpu").contiguous()
    targets_raw = teacher.residual_update(hidden.to(device))
    if not isinstance(targets_raw, torch.Tensor) or targets_raw.dtype != FIXTURE_DTYPE:
        raise FixtureProvenanceError("Teacher residual update must already be FP32; no silent cast")
    targets = targets_raw.detach().to("cpu").contiguous()
    if tuple(hidden.shape) != (FORMAL_SEQUENCES, FORMAL_LENGTH, 768):
        raise FixtureProvenanceError(
            f"the Teacher prefix produced {tuple(hidden.shape)}; the frozen block-5 input is "
            f"({FORMAL_SEQUENCES}, {FORMAL_LENGTH}, 768)")
    if targets.shape != hidden.shape:
        raise FixtureProvenanceError(
            f"the Teacher block-5 update {tuple(targets.shape)} does not match the block-5 input "
            f"{tuple(hidden.shape)}")
    if not torch.isfinite(hidden).all() or not torch.isfinite(targets).all():
        raise FixtureProvenanceError("the formal fixture contains non-finite Teacher values")

    fixture = {
        "token_ids": token_ids,
        "hidden": hidden,
        "targets": targets,
        "provenance": {
            "namespace": namespace,
            "teacher_identity": (
                cmr1_teacher.assert_pinned_teacher_wrapper(teacher)
                if cmr1_rng.is_canonical_qualification_namespace(namespace) else "TEST-ONLY"),
            "chain": "role -> accepted tokens -> Teacher embedding/prefix 0-4 -> exact model-forward "
                     "block-5 input -> "
                     "Teacher block-5 update -> fixture",
            "token_bank_identity": token_bank_identity(token_ids),
            "block5_input_identity": cmr1_objects.tensor_object_identity(
                {"hidden": hidden}, semantics={"hidden": "exact block-5 boundary input, float32"}),
            "block5_target_identity": cmr1_objects.tensor_object_identity(
                {"targets": targets},
                semantics={"targets": "frozen Teacher block-5 residual update, float32"}),
            "teacher_interface": ["prefix_states", "residual_update"],
            "accepted_token_set": [ACCEPTED_TOKEN_MIN, ACCEPTED_TOKEN_MAX_EXCLUSIVE],
            "externally_supplied_tensors_accepted": False,
        },
    }
    assert_fixture_provenance(fixture, teacher=teacher, device=device)
    return fixture


def token_bank_identity(token_ids: torch.Tensor) -> str:
    """Content identity of the sampled token bank."""
    return cmr1_objects.tensor_object_identity(
        {"token_ids": token_ids},
        semantics={"token_ids": "frozen Native sampling law token ids, int64, accepted set 0..50276"})


def assert_fixture_provenance(fixture: Mapping[str, torch.Tensor], *, teacher,
                              device: str | None = None) -> dict:
    """Prove that the fixture's Teacher tensors came from **those exact token ids**.

    Recomputes the block-5 input and the residual update from the fixture's own token bank through the
    frozen Teacher path and requires exact agreement.  A fixture whose hidden states or targets were
    altered -- or which pairs a token bank with another bank's Teacher tensors -- fails closed here.
    """
    for key in ("token_ids", "hidden", "targets"):
        if key not in fixture:
            raise FixtureProvenanceError(f"the fixture is missing {key!r}")
    token_ids = fixture["token_ids"]
    assert_accepted_token_ids(token_ids)
    if device is None:
        model = getattr(teacher, "model", None)
        device = str(next(model.parameters()).device) if model is not None else "cpu"
    if not isinstance(fixture.get("provenance"), Mapping) or not isinstance(
            fixture["provenance"].get("namespace"), str):
        raise FixtureProvenanceError("formal fixture has no construction-namespace provenance")
    if cmr1_rng.is_canonical_qualification_namespace(fixture["provenance"]["namespace"]):
        from silent_teacher.cmr1_teacher import assert_pinned_teacher_wrapper
        if fixture["provenance"].get("teacher_identity") != assert_pinned_teacher_wrapper(teacher):
            raise FixtureProvenanceError("formal fixture Teacher identity differs from the pinned loader")
    elif fixture["provenance"].get("teacher_identity") != "TEST-ONLY":
        raise FixtureProvenanceError("TEST-ONLY fixture cannot claim a governed Teacher identity")

    if any(fixture[key].dtype != FIXTURE_DTYPE for key in ("hidden", "targets")):
        raise FixtureProvenanceError("governed hidden/target tensors must already be FP32")
    recomputed_hidden_raw = (teacher.capture_boundary(token_ids.to(device))
                             if cmr1_rng.is_canonical_qualification_namespace(
                                 fixture["provenance"]["namespace"])
                             else teacher.prefix_states(token_ids.to(device)))
    if recomputed_hidden_raw.dtype != FIXTURE_DTYPE:
        raise FixtureProvenanceError("Teacher prefix output is not FP32; no silent cast")
    recomputed_hidden = recomputed_hidden_raw.detach().to("cpu").contiguous()
    if not torch.equal(recomputed_hidden, fixture["hidden"].detach().to("cpu")):
        raise FixtureProvenanceError(
            "HARD STOP - the fixture's block-5 input is not the Teacher prefix output for its own "
            "token bank; the provenance chain is broken (altered hidden states or a mismatched bank)")
    recomputed_targets_raw = teacher.residual_update(recomputed_hidden.to(device))
    if recomputed_targets_raw.dtype != FIXTURE_DTYPE:
        raise FixtureProvenanceError("Teacher residual update is not FP32; no silent cast")
    recomputed_targets = recomputed_targets_raw.detach().to("cpu").contiguous()
    if not torch.equal(recomputed_targets, fixture["targets"].detach().to("cpu")):
        raise FixtureProvenanceError(
            "HARD STOP - the fixture's targets are not the frozen block-5 update for its own block-5 "
            "input; the provenance chain is broken")

    for key in ("hidden", "targets"):
        if fixture[key].dtype != FIXTURE_DTYPE:
            raise FixtureProvenanceError(
                f"HARD STOP - the fixture's {key} has dtype {fixture[key].dtype}; governed fixture "
                "tensors are FP32 and are never silently cast")
    expected = {"token_bank_identity": token_bank_identity(token_ids),
                "block5_input_identity": cmr1_objects.tensor_object_identity(
                    {"hidden": fixture["hidden"]},
                    semantics={"hidden": "exact block-5 boundary input, float32"}),
                "block5_target_identity": cmr1_objects.tensor_object_identity(
                    {"targets": fixture["targets"]},
                    semantics={"targets": "frozen Teacher block-5 residual update, float32"})}
    if not isinstance(fixture.get("provenance"), Mapping) or any(
            fixture["provenance"].get(key) != value for key, value in expected.items()):
        raise FixtureProvenanceError("formal fixture provenance identities do not bind its tensors")
    return {"provenance": "VERIFIED", "token_bank_identity": token_bank_identity(token_ids),
            "externally_supplied_tensors_accepted": False}


def formal_fixture_identity(fixture: Mapping[str, object]) -> str:
    """Canonical content identity of the formal fixture object.

    Only the tensor members enter the tensor digest; the provenance record is carried in ``extra`` so the
    identity covers the chain too, without a non-tensor member breaking the digest.
    """
    tensors = {name: value for name, value in fixture.items()
               if isinstance(value, torch.Tensor)}
    return cmr1_objects.tensor_object_identity(
        tensors,
        semantics={
            "token_ids": "frozen Native sampling law token ids, int64, accepted set 0..50276",
            "hidden": "block-5 boundary input hidden states, float32",
            "targets": "declared Teacher block-5 residual update, float32",
            "labels": "training labels (equals targets for the Native arm), float32",
        },
        extra={"fixture_role": "fixture/formal", "sequences": FORMAL_SEQUENCES,
               "length": FORMAL_LENGTH, "token_policy": "range(0, 50277)",
               "provenance": dict(fixture.get("provenance", {}))},
    )


# --------------------------------------------------------------------------- Q_pos construction
def build_native_qpos_permutations(role_seed: int, *, namespace: str,
                                   donors: int = FORMAL_SEQUENCES,
                                   positions: int = FORMAL_LENGTH,
                                   generator: torch.Generator | None = None,
                                   capability=None, runtime_context=None
                                   ) -> list[list[int]]:
    """The realized per-position permutation object ``(pi_0 ... pi_{T-1})``.

    One **uniform** permutation over ``donors`` indices per position, drawn independently for each
    position, with **no derangement constraint** (protocol 6.2).
    """
    _refuse_governed(namespace, "Q_pos permutation object", capability=capability,
                     runtime_context=runtime_context)
    if donors <= 1 or positions <= 0:
        raise FixtureConstructionError("permutation dimensions must be positive and donors > 1")
    if cmr1_rng.is_canonical_qualification_namespace(namespace) and generator is not None:
        raise FixtureConstructionError("governed Q_pos permutations must consume the frozen role seed directly")
    if generator is None:
        generator = _generator(role_seed)
    permutations: list[list[int]] = []
    for _ in range(positions):
        order = torch.randperm(donors, generator=generator, dtype=torch.int64)
        permutations.append(order.tolist())
    for index, perm in enumerate(permutations):
        if sorted(perm) != list(range(donors)):
            raise FixtureConstructionError(
                f"HARD STOP - position {index} is not a permutation of 0..{donors - 1}")
    return permutations


def apply_qpos_permutation(native: torch.Tensor, permutations: list[list[int]]) -> torch.Tensor:
    """``H_pos[n, t] = H_nat[pi_t(n), t]`` over the sequence axis.

    ``native`` is ``[N, T, ...]``; the permutation object has one entry per position ``t``.
    """
    if native.dim() < 2:
        raise FixtureConstructionError("native bank must be at least 2-D [sequences, positions, ...]")
    donors, positions = native.shape[0], native.shape[1]
    if len(permutations) != positions:
        raise FixtureConstructionError(
            f"permutation object has {len(permutations)} positions, bank has {positions}")
    try:
        cmr1_objects.permutation_object_identity(permutations)  # strict before torch converts
    except cmr1_objects.SerializationError as exc:
        raise FixtureConstructionError(str(exc)) from exc
    index = torch.tensor(permutations, dtype=torch.int64, device=native.device)                 # [T, N]
    if index.shape != (positions, donors):
        raise FixtureConstructionError(
            f"permutation object must be {positions} x {donors}, got {tuple(index.shape)}")
    # Fail closed on a non-permutation: duplicated or out-of-range indices would break the exact
    # position-wise multiset invariant that Q2-5/Q2-6 assert.
    for position in range(positions):
        if sorted(permutations[position]) != list(range(donors)):
            raise FixtureConstructionError(
                f"HARD STOP - position {position} is not a permutation of 0..{donors - 1}")
    gathered = torch.gather(native, 0, index.t().reshape(donors, positions,
                                                         *([1] * (native.dim() - 2))).expand(
        donors, positions, *native.shape[2:]))
    return gathered.contiguous()


def assert_positionwise_multiset_invariant(native: torch.Tensor,
                                           qpos: torch.Tensor) -> None:
    """Q2-6: at every position the Q_pos multiset equals the Native multiset.

    **Exact whole-vector multiset equality.** Each hidden vector at a position is treated as one
    indivisible element and compared through its canonical byte representation.  Sorting the
    coordinates independently is **invalid** - it would accept a hybrid vector set that is not a
    permutation of the Native rows at all - so it is not used.

    The frozen permutation law permits an identity permutation, so an identity outcome is a legal
    realization and is **not** rejected here: this checker validates the invariant, and imposes no
    additional non-identity requirement.
    """
    if native.shape != qpos.shape:
        raise FixtureConstructionError("Native and Q_pos banks must share a shape")
    donors, positions = native.shape[0], native.shape[1]
    flat_native = native.reshape(donors, positions, -1)
    flat_qpos = qpos.reshape(donors, positions, -1)
    for position in range(positions):
        native_vectors = sorted(_row_bytes(flat_native[row, position, :])
                                for row in range(donors))
        qpos_vectors = sorted(_row_bytes(flat_qpos[row, position, :]) for row in range(donors))
        if native_vectors != qpos_vectors:
            raise FixtureConstructionError(
                f"HARD STOP - position {position}: the Q_pos multiset differs from the Native "
                "multiset as a multiset of whole vectors (exact invariant violated)")


def _row_bytes(vector: torch.Tensor) -> bytes:
    """Canonical byte representation of one whole hidden vector."""
    return vector.detach().to("cpu").contiguous().numpy().tobytes(order="C")


def build_qpos_bank(native: torch.Tensor, role_seed: int, *, namespace: str,
                    capability=None, runtime_context=None
                    ) -> tuple[torch.Tensor, list[list[int]]]:
    """Build the derived Q_pos bank and return it with the realized permutation object.

    The Q_pos bank is a **derived** realized object: it receives no seed of its own.
    """
    if cmr1_rng.is_canonical_qualification_namespace(namespace):
        from silent_teacher import cmr1_bootstrap
        cmr1_bootstrap.assert_governed_entry(
            runtime_context, scope="qualification_identity_realization",
            inputs={"Native formal hidden bank": native})
        if native.shape != (FORMAL_SEQUENCES, FORMAL_LENGTH, 768):
            raise FixtureConstructionError("governed Q_pos requires the complete formal Native bank")
    permutations = build_native_qpos_permutations(
        role_seed, namespace=namespace, donors=native.shape[0], positions=native.shape[1],
        capability=capability, runtime_context=runtime_context)
    qpos = apply_qpos_permutation(native, permutations)
    assert_positionwise_multiset_invariant(native, qpos)
    return qpos, permutations


def qpos_permutation_identity(permutations: list[list[int]]) -> str:
    return cmr1_objects.permutation_object_identity(permutations)


def build_labeled_qpos_fixture(formal_fixture: Mapping[str, object], role_seed: int, *,
                               namespace: str, teacher, capability=None,
                               runtime_context=None) -> dict:
    """Realize and store the Q_pos input/labels before any later fresh-label Q2 comparison."""
    _refuse_governed(namespace, "labeled Q_pos fixture", capability=capability,
                     runtime_context=runtime_context, teacher=teacher)
    if formal_fixture.get("provenance", {}).get("namespace") != namespace:
        raise FixtureProvenanceError("Q_pos and Native fixture namespaces differ")
    assert_fixture_provenance(formal_fixture, teacher=teacher)
    native_identity = formal_fixture_identity(formal_fixture)
    qpos, permutations = build_qpos_bank(
        formal_fixture["hidden"], role_seed, namespace=namespace,
        capability=capability, runtime_context=runtime_context)
    device = (next(teacher.model.parameters()).device if hasattr(teacher, "model")
              else torch.device("cpu"))
